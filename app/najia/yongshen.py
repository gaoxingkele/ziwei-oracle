# -*- coding: utf-8 -*-
"""用神取法（基于卜筮正宗/增删卜易主流规则的简化版）。

输入: question 文本 + 占问者性别
输出: 用神所属六亲名（'兄弟'/'父母'/'官鬼'/'妻财'/'子孙'）或 None（默认世爻为用）
"""
from __future__ import annotations

# 关键词 → 六亲；按优先级前置匹配
RULES: list[tuple[tuple[str, ...], str, str]] = [
    # (关键词, 六亲, 备注)
    (("求财", "财运", "投资", "生意", "买卖", "做生意", "发财", "彩票", "中奖",
      "工资", "薪水", "奖金", "理财", "股票", "基金", "钱财", "破财"), "妻财", "求财类"),
    (("升迁", "升职", "工作", "求职", "面试", "考试", "高考", "考研", "公务员",
      "官运", "事业", "前途", "上司", "领导", "考公", "考编", "录取"), "官鬼", "求官/工作"),
    (("文书", "合同", "证件", "证书", "执照", "文章", "论文", "学业", "学习",
      "房子", "买房", "卖房", "家宅", "搬家", "车", "买车", "卖车", "搬迁"), "父母", "文书/家宅/车房"),
    (("子女", "孩子", "求子", "怀孕", "生育", "晚辈", "学生", "宠物", "猫", "狗",
      "医药", "看病", "求医"), "子孙", "子嗣/医药/宠物"),
    (("兄弟", "姐妹", "朋友", "同事", "合伙", "合伙人", "对手", "竞争"), "兄弟", "同辈"),
    # 婚恋（性别相关，最后处理）
    (("婚姻", "感情", "对象", "恋爱", "找对象", "脱单", "结婚", "离婚",
      "外遇", "桃花", "另一半", "伴侣", "相亲", "暗恋", "追求"), "__love__", "婚恋: 男看财、女看官"),
    # 疾病：问他人病另算，这里默认问己病
    (("生病", "疾病", "病情", "身体", "健康"), "__self__", "病: 自身→世爻，特定亲属另判"),
]


def take_yongshen(question: str, gender: str = "") -> str | None:
    """根据 question 取用神所属六亲。

    返回:
        '兄弟'/'父母'/'官鬼'/'妻财'/'子孙' — 命中六亲规则
        None — 未匹配，由调用方默认以世爻为用神
    """
    q = (question or "").strip()
    if not q:
        return None
    for keywords, qin, _ in RULES:
        if any(kw in q for kw in keywords):
            if qin == "__love__":
                return "妻财" if "男" in (gender or "") else "官鬼" if "女" in (gender or "") else "妻财"
            if qin == "__self__":
                return None
            return qin
    return None
